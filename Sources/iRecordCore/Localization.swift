import Foundation

public enum AppLanguage: String, Codable, CaseIterable, Identifiable, Sendable {
    case system
    case english = "en"
    case simplifiedChinese = "zh-Hans"
    case japanese = "ja"
    case korean = "ko"
    case german = "de"
    case french = "fr"
    case spanish = "es"

    public var id: String { rawValue }

    public var resolved: AppLanguage {
        guard self == .system else { return self }
        let preferred = Locale.preferredLanguages.first?.lowercased() ?? "en"
        if preferred.hasPrefix("zh") { return .simplifiedChinese }
        if preferred.hasPrefix("ja") { return .japanese }
        if preferred.hasPrefix("ko") { return .korean }
        if preferred.hasPrefix("de") { return .german }
        if preferred.hasPrefix("fr") { return .french }
        if preferred.hasPrefix("es") { return .spanish }
        return .english
    }

    public var displayName: String {
        switch self {
        case .system: return L10n.t("lang.system")
        case .english: return "English"
        case .simplifiedChinese: return "简体中文"
        case .japanese: return "日本語"
        case .korean: return "한국어"
        case .german: return "Deutsch"
        case .french: return "Français"
        case .spanish: return "Español"
        }
    }
}

public enum L10n {
    /// The active UI language. Updated by SettingsStore.
    public static var current: AppLanguage = .english

    public static func t(_ key: String) -> String {
        t(key, current)
    }

    public static func t(_ key: String, _ language: AppLanguage) -> String {
        let resolved = language.resolved
        if let value = tables[resolved]?[key] { return value }
        return tables[.english]?[key] ?? key
